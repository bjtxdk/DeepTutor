import { fireEvent, render, screen, within } from '@testing-library/react'
import { beforeEach, expect, it, vi } from 'vitest'
import { WritingFoundationsUnit } from '@/features/french-learning/components/WritingFoundationsUnit'
import { browserStorage } from '@/shared/storage'

beforeEach(() => localStorage.clear())
function lesson(name: string) { fireEvent.click(within(screen.getByRole('navigation', { name: 'Leçons de base' })).getByRole('button', { name: new RegExp(name) })) }
it('starts with complete sentences and lets hints fade without losing the learner’s own sentence', () => {
  render(<WritingFoundationsUnit scope="student" />)
  expect(within(screen.getByRole('navigation', { name: 'Leçons de base' })).getAllByRole('button')).toHaveLength(6)
  fireEvent.click(screen.getByLabelText('Pendant la récréation.'))
  expect(screen.getByText(/Essaie encore/)).toBeInTheDocument()
  fireEvent.click(screen.getByLabelText('Les élèves discutent pendant la récréation.'))
  expect(screen.getByText(/Bien vu/)).toBeInTheDocument()
  fireEvent.change(screen.getByRole('textbox', { name: 'Qui ?' }), { target: { value: 'Ma classe' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Fait quoi ?' }), { target: { value: 'prépare un spectacle' } })
  expect(screen.getByText(/Ma classe prépare un spectacle/)).toBeInTheDocument()
  fireEvent.change(screen.getByRole('textbox', { name: 'Mon essai personnel' }), { target: { value: 'Ma classe prépare un spectacle.' } })
  fireEvent.click(screen.getByRole('button', { name: 'Masquer les aides' }))
  expect(screen.queryByRole('textbox', { name: 'Qui ?' })).toBeNull()
  expect(screen.getByRole('textbox', { name: 'Mon essai personnel' })).toHaveValue('Ma classe prépare un spectacle.')
  fireEvent.click(screen.getByRole('button', { name: 'Afficher les aides' }))
  expect(screen.getByRole('textbox', { name: 'Qui ?' })).toHaveValue('Ma classe')
})
it('checks paragraph ordering, gives a retry hint, and lets keyboard-accessible buttons repair the order', () => {
  render(<WritingFoundationsUnit scope="student" />)
  lesson('Construire un paragraphe')
  fireEvent.click(screen.getByRole('button', { name: 'Vérifier l’ordre' }))
  expect(screen.getByText(/À revoir : trouve d’abord/)).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Monter la phrase 2' }))
  expect(screen.queryByText(/À revoir : trouve d’abord/)).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Monter la phrase 4' }))
  fireEvent.click(screen.getByRole('button', { name: 'Monter la phrase 3' }))
  fireEvent.click(screen.getByRole('button', { name: 'Vérifier l’ordre' }))
  expect(screen.getByText(/L’ordre du modèle est retrouvé/)).toBeInTheDocument()
})
it('saves separate sentence trials, shared plan, final draft, choices and review checks across reloads', () => {
  const view = render(<WritingFoundationsUnit scope="student" />)
  fireEvent.change(screen.getByRole('textbox', { name: 'Mon essai personnel' }), { target: { value: 'Les élèves lisent.' } })
  fireEvent.click(screen.getByLabelText('Les élèves discutent pendant la récréation.'))
  lesson('Préparer')
  fireEvent.change(screen.getByRole('textbox', { name: 'Ma proposition' }), { target: { value: 'Un coin lecture' } })
  lesson('Écrire et relire')
  expect(screen.getByRole('textbox', { name: 'Ma proposition' })).toHaveValue('Un coin lecture')
  fireEvent.change(screen.getByRole('textbox', { name: 'Mon petit texte' }), { target: { value: 'Je propose un coin lecture dans la cour.' } })
  fireEvent.click(screen.getByLabelText('Chaque phrase dit clairement ce qui se passe.'))
  fireEvent.click(screen.getByRole('button', { name: 'J’ai travaillé cette leçon' }))
  view.unmount()
  render(<WritingFoundationsUnit scope="student" />)
  expect(screen.getByRole('textbox', { name: 'Mon petit texte' })).toHaveValue('Je propose un coin lecture dans la cour.')
  expect(screen.getByLabelText('Chaque phrase dit clairement ce qui se passe.')).toBeChecked()
  expect(screen.getByRole('progressbar')).toHaveAttribute('value', '1')
  lesson('Une phrase complète')
  expect(screen.getByRole('textbox', { name: 'Mon essai personnel' })).toHaveValue('Les élèves lisent.')
  expect(screen.getByLabelText('Les élèves discutent pendant la récréation.')).toBeChecked()
})
it('isolates work by account/workspace scope and reports a failed save', () => {
  const view = render(<WritingFoundationsUnit scope="account-a/workspace-a" />)
  fireEvent.change(screen.getByRole('textbox', { name: 'Mon essai personnel' }), { target: { value: 'Private practice' } })
  fireEvent.click(screen.getByRole('button', { name: 'Enregistrer mes bases' }))
  view.unmount()
  render(<WritingFoundationsUnit scope="account-b/workspace-a" />)
  expect(screen.getByRole('textbox', { name: 'Mon essai personnel' })).toHaveValue('')
  vi.spyOn(browserStorage, 'write').mockReturnValueOnce(false)
  fireEvent.click(screen.getByRole('button', { name: 'Enregistrer mes bases' }))
  expect(screen.getByText(/Enregistrement indisponible/)).toBeInTheDocument()
})
it('ignores malformed saved data and keeps the first lesson available', () => {
  localStorage.setItem('deeptutor:v2:local:french-learning:foundations:broken', '{bad')
  render(<WritingFoundationsUnit scope="broken" />)
  expect(screen.getByRole('heading', { name: '1. Une phrase complète' })).toBeInTheDocument()
})
